#!/usr/bin/env node
/* Turn every fixed hex colour inside a CSS rule into a theme colour
 * (var(--c-<hex>)), so src/theme.js can recolour the whole interface.
 *
 *   node tools/theme-tokenize.cjs          rewrite styles/*.css and src/theme-colors.js
 *   node tools/theme-tokenize.cjs --check  exit 1 if any rule still has a fixed colour
 *
 * The first :root block of styles/main.css (the named palette: --bg, --panel,
 * --accent ...) stays as it is; src/theme.js sets those by name. Everything
 * else gets one --c-<hex> variable per distinct colour, defined (with its
 * original value as the default) in a generated :root block, and listed in
 * src/theme-colors.js. Re-running is safe: it only converts what is left.
 */
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const FILES = ['styles/main.css', 'styles/lasso-tb.css'];
const BEGIN = '/* theme-colors: generated by tools/theme-tokenize.cjs, do not edit */';
const END = '/* end theme-colors */';
const HEX = /#([0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{4}|[0-9a-fA-F]{3})\b/g;

const norm = h => {
  h = h.toLowerCase();
  if (h.length === 3 || h.length === 4) h = h.split('').map(c => c + c).join('');
  return h;
};

function tokenize(text, used, skipFirstRoot) {
  // cut out a previous generated block; it is rebuilt from `used`
  const b = text.indexOf(BEGIN);
  if (b >= 0) {
    const e = text.indexOf(END, b);
    for (const m of text.slice(b, e).matchAll(/--c-([0-9a-f]+):\s*#([0-9a-f]+)/g)) used.set(m[1], '#' + m[2]);
    text = text.slice(0, b) + text.slice(e + END.length).replace(/^\n/, '');
  }
  let rootDone = !skipFirstRoot, out = '', i = 0, left = 0;
  // innermost { ... } blocks hold declarations; selectors (#ids) sit outside them
  while (i < text.length) {
    const open = text.indexOf('{', i);
    if (open < 0) break;
    const close = text.indexOf('}', open);
    const nextOpen = text.indexOf('{', open + 1);
    if (nextOpen >= 0 && nextOpen < close) { i = open + 1; continue; }   // not innermost
    const head = text.slice(Math.max(text.lastIndexOf('}', open), text.lastIndexOf('{', open - 1), 0), open);
    let body = text.slice(open + 1, close);
    const isRoot = /(^|[\s,}])?:root\s*$/.test(head.trim()) || head.trim().endsWith(':root');
    if (isRoot && !rootDone) rootDone = true;
    else if (!/@font-face/.test(head)) {
      body = body.replace(HEX, (m, h) => {
        if (/var\(--c-/.test(m)) return m;
        const k = norm(h);
        used.set(k, '#' + k);
        return 'var(--c-' + k + ')';
      });
    }
    out += text.slice(left, open + 1) + body + '}';
    left = close + 1;
    i = close + 1;
  }
  return out + text.slice(left);
}

function leftovers(text) {
  const b = text.indexOf(BEGIN), e = text.indexOf(END);
  if (b >= 0) text = text.slice(0, b) + text.slice(e + END.length);
  // drop the named palette (first :root) and font faces, then look for hex in rule bodies
  text = text.replace(/:root\s*\{[^}]*\}/, '').replace(/@font-face\s*\{[^}]*\}/g, '');
  const hits = [];
  for (const m of text.matchAll(/\{([^{}]*)\}/g)) for (const h of m[1].matchAll(HEX)) hits.push(h[0]);
  return hits;
}

const check = process.argv.includes('--check');
const used = new Map();
let bad = 0;
for (const f of FILES) {
  const p = path.join(ROOT, f);
  const src = fs.readFileSync(p, 'utf8');
  if (check) {
    const l = leftovers(src);
    if (l.length) { console.log(f + ': fixed colours outside the theme: ' + [...new Set(l)].join(' ')); bad++; }
    continue;
  }
  let out = tokenize(src, used, f === 'styles/main.css');
  if (f === 'styles/main.css') {
    // put the generated block right after the named palette
    const at = out.indexOf('}', out.search(/:root\s*\{/)) + 1;
    const keys = [...used.keys()].sort();
    const block = '\n' + BEGIN + '\n:root{\n' + keys.map(k => '  --c-' + k + ':' + used.get(k) + ';').join('\n') + '\n}\n' + END;
    out = out.slice(0, at) + block + out.slice(at);
  }
  fs.writeFileSync(p, out);
}
if (check) process.exit(bad ? 1 : 0);
// lasso-tb.css was processed after main.css: make sure its colours are in the block
const mainP = path.join(ROOT, 'styles/main.css');
let main = fs.readFileSync(mainP, 'utf8');
const keys = [...used.keys()].sort();
main = main.replace(new RegExp(BEGIN.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&') + '[\\s\\S]*?' + END.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&')),
  BEGIN + '\n:root{\n' + keys.map(k => '  --c-' + k + ':' + used.get(k) + ';').join('\n') + '\n}\n' + END);
fs.writeFileSync(mainP, main);
fs.writeFileSync(path.join(ROOT, 'src/theme-colors.js'),
  '/* Generated by tools/theme-tokenize.cjs: the interface colours src/theme.js recolours. */\n' +
  '(function (OT) { OT.THEME_COLORS = ' + JSON.stringify(Object.fromEntries(keys.map(k => [k, used.get(k)]))) + '; })(window.OT = window.OT || {});\n');
console.log(keys.length + ' theme colours');
