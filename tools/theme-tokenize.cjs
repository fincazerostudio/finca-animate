#!/usr/bin/env node
/* Turn every fixed hex colour inside a CSS rule into a theme colour
 * (var(--c-<hex>)), so src/theme.js can recolour the whole interface.
 *
 *   node tools/theme-tokenize.cjs          rewrite the styles, styles/theme-colors.css
 *                                          and src/theme-colors.js
 *   node tools/theme-tokenize.cjs --check  exit 1 if any rule still has a fixed colour
 *
 * Sources: styles/main.css, styles/lasso-tb.css and the <style> block of
 * pen/pen.html (the pen window). The first :root block of styles/main.css
 * (the named palette: --bg, --panel, --accent ...) stays as it is; src/theme.js
 * sets those by name. Every other colour gets one --c-<hex> variable, defined
 * with its original value in styles/theme-colors.css (loaded by both windows)
 * and listed in src/theme-colors.js. Re-running only converts what is left.
 */
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const CSS = ['styles/main.css', 'styles/lasso-tb.css'];
const HTML = ['pen/pen.html'];
const OUT_CSS = 'styles/theme-colors.css';
const OUT_JS = 'src/theme-colors.js';
// an older layout kept the generated block inside main.css
const BEGIN = '/* theme-colors: generated by tools/theme-tokenize.cjs, do not edit */';
const END = '/* end theme-colors */';
const HEX = /#([0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{4}|[0-9a-fA-F]{3})\b/g;

const norm = h => {
  h = h.toLowerCase();
  if (h.length === 3 || h.length === 4) h = h.split('').map(c => c + c).join('');
  return h;
};

function dropOldBlock(text, used) {
  const b = text.indexOf(BEGIN);
  if (b < 0) return text;
  const e = text.indexOf(END, b);
  for (const m of text.slice(b, e).matchAll(/--c-([0-9a-f]+):\s*#([0-9a-f]+)/g)) used.set(m[1], '#' + m[2]);
  return text.slice(0, b) + text.slice(e + END.length).replace(/^\n/, '');
}

// convert colours in innermost { } blocks (declarations); selectors (#ids) sit outside
function tokenizeCss(text, used, skipFirstRoot) {
  let rootDone = !skipFirstRoot, out = '', i = 0, left = 0;
  while (i < text.length) {
    const open = text.indexOf('{', i);
    if (open < 0) break;
    const close = text.indexOf('}', open);
    const nextOpen = text.indexOf('{', open + 1);
    if (nextOpen >= 0 && nextOpen < close) { i = open + 1; continue; }
    const head = text.slice(Math.max(text.lastIndexOf('}', open), text.lastIndexOf('{', open - 1), 0), open);
    let body = text.slice(open + 1, close);
    const isRoot = head.trim().endsWith(':root');
    if (isRoot && !rootDone) rootDone = true;
    else if (!/@font-face/.test(head)) {
      body = body.replace(HEX, (m, h) => { const k = norm(h); used.set(k, '#' + k); return 'var(--c-' + k + ')'; });
    }
    out += text.slice(left, open + 1) + body + '}';
    left = close + 1;
    i = close + 1;
  }
  return out + text.slice(left);
}

function leftovers(css, skipRoot) {
  if (skipRoot) css = css.replace(/:root\s*\{[^}]*\}/, '');
  css = css.replace(/@font-face\s*\{[^}]*\}/g, '');
  const hits = [];
  for (const m of css.matchAll(/\{([^{}]*)\}/g)) for (const h of m[1].matchAll(HEX)) hits.push(h[0]);
  return hits;
}

const styleBlock = html => { const m = html.match(/<style>([\s\S]*?)<\/style>/); return m ? { css: m[1], at: m.index + '<style>'.length } : null; };

const check = process.argv.includes('--check');
const used = new Map();
let bad = 0;
for (const f of CSS) {
  const p = path.join(ROOT, f);
  let src = fs.readFileSync(p, 'utf8');
  if (check) {
    const l = leftovers(src.replace(new RegExp(BEGIN.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&') + '[\\s\\S]*?' + END.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&')), ''), f === 'styles/main.css');
    if (l.length) { console.log(f + ': fixed colours outside the theme: ' + [...new Set(l)].join(' ')); bad++; }
    continue;
  }
  src = dropOldBlock(src, used);
  fs.writeFileSync(p, tokenizeCss(src, used, f === 'styles/main.css'));
}
for (const f of HTML) {
  const p = path.join(ROOT, f);
  const html = fs.readFileSync(p, 'utf8');
  const sb = styleBlock(html);
  if (!sb) continue;
  if (check) {
    const l = leftovers(sb.css, false);
    if (l.length) { console.log(f + ': fixed colours outside the theme: ' + [...new Set(l)].join(' ')); bad++; }
    continue;
  }
  const css = tokenizeCss(sb.css, used, false);
  fs.writeFileSync(p, html.slice(0, sb.at) + css + html.slice(sb.at + sb.css.length));
}
if (check) {
  // every colour used must be defined
  const defined = fs.readFileSync(path.join(ROOT, OUT_CSS), 'utf8');
  for (const f of CSS.concat(HTML)) {
    for (const m of fs.readFileSync(path.join(ROOT, f), 'utf8').matchAll(/var\(--c-([0-9a-f]+)\)/g)) {
      if (!defined.includes('--c-' + m[1] + ':')) { console.log(f + ': --c-' + m[1] + ' is not defined in ' + OUT_CSS); bad++; }
    }
  }
  process.exit(bad ? 1 : 0);
}
// keep colours defined before (a source may have been edited away from them)
try {
  for (const m of fs.readFileSync(path.join(ROOT, OUT_CSS), 'utf8').matchAll(/--c-([0-9a-f]+):\s*#([0-9a-f]+)/g)) if (!used.has(m[1])) used.set(m[1], '#' + m[2]);
} catch (e) { /* first run */ }
const keys = [...used.keys()].sort();
fs.writeFileSync(path.join(ROOT, OUT_CSS),
  '/* Theme colours: generated by tools/theme-tokenize.cjs, do not edit.\n' +
  '   Each is an interface colour at its Classic value; src/theme.js recolours them. */\n' +
  ':root{\n' + keys.map(k => '  --c-' + k + ':' + used.get(k) + ';').join('\n') + '\n}\n');
fs.writeFileSync(path.join(ROOT, OUT_JS),
  '/* Generated by tools/theme-tokenize.cjs: the interface colours src/theme.js recolours. */\n' +
  '(function (OT) { OT.THEME_COLORS = ' + JSON.stringify(Object.fromEntries(keys.map(k => [k, used.get(k)]))) + '; })(window.OT = window.OT || {});\n');
console.log(keys.length + ' theme colours');
